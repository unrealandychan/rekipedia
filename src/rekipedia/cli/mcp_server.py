class _StoreCache:
    """
    Lazy-loading, auto-refreshing store cache.

    Symbols and relationships are loaded on first access and reloaded
    automatically whenever the DB file's mtime changes (i.e. after reki scan).
    This means the MCP server never needs to be restarted after a rescan.
    """

    def __init__(self, output_dir: str):
        self._rekipedia_dir = Path(output_dir) / ".rekipedia"
        self.db_path = self._resolve_db_path()
        self._store = None
        self._symbols: list = []
        self._rels: list = []
        self._mtime: float = 0.0
        # Pre-built indices for O(1) / O(log n) lookups
        self._name_index: dict[str, list] = {}   # lower(name) → [symbols]
        self._file_index: dict[str, list] = {}   # lower(file) → [symbols]
        self._callers_index: dict[str, list] = {}  # symbol → [callers]
        self._callees_index: dict[str, list] = {}  # symbol → [callees]

    def _resolve_db_path(self) -> Path:
        store = self._rekipedia_dir / "store.db"
        if store.exists():
            return store
        alt = self._rekipedia_dir / "rekipedia.db"
        if alt.exists():
            return alt
        return store  # default to store.db (will not exist yet if unscanned)

    # ── public accessors ──────────────────────────────────────────────────────

    @property
    def available(self) -> bool:
        return self.db_path.exists()

    @property
    def symbols(self) -> list:
        self._refresh()
        return self._symbols

    @property
    def rels(self) -> list:
        self._refresh()
        return self._rels

    def search_by_name(self, query: str) -> list:
        self._refresh()
        q = query.lower()
        results = []
        for key, syms in self._name_index.items():
            if q in key:
                results.extend(syms)
        return results[:50]

    def symbols_for_file(self, file_arg: str) -> list:
        """Match by suffix so partial paths work (e.g. 'foo.py' matches '/abs/src/foo.py')."""
        self._refresh()
        fa = file_arg.lower().replace("\\", "/")
        results = []
        for key, syms in self._file_index.items():
            if key.endswith(fa) or fa in key:
                results.extend(syms)
        return results

    def callers_callees(self, symbol: str) -> tuple[list, list]:
        self._refresh()
        return (
            self._callers_index.get(symbol, [])[:30],
            self._callees_index.get(symbol, [])[:30],
        )

    # ── internals ─────────────────────────────────────────────────────────────

    def _refresh(self):
        self.db_path = self._resolve_db_path()
        if not self.db_path.exists():
            return
        try:
            current_mtime = self.db_path.stat().st_mtime
        except OSError:
            return
        if current_mtime <= self._mtime:
            return  # DB unchanged — use cached data
        self._load(current_mtime)

    def _load(self, mtime: float):
        try:
            from rekipedia.storage.sqlite_store import SqliteStore
            with SqliteStore(self.db_path) as store:
                run_id = store.latest_run_id()
                if not run_id:
                    return
                symbols = store.get_all_symbols(run_id)
                rels = store.get_all_relationships(run_id)
                self._store = store
                self._symbols = symbols
                self._rels = rels
            self._mtime = mtime
            self._rebuild_indices(symbols, rels)
        except Exception:
            pass  # silently keep stale data if reload fails

    def _rebuild_indices(self, symbols, rels):
        name_idx: dict[str, list] = {}
        file_idx: dict[str, list] = {}
        for s in symbols:
            name = (s.name if hasattr(s, "name") else s.get("name", "")).lower()
            file = (s.file if hasattr(s, "file") else s.get("file", "")).lower().replace("\\", "/")
            name_idx.setdefault(name, []).append(s)
            if file:
                file_idx.setdefault(file, []).append(s)
        self._name_index = name_idx
        self._file_index = file_idx

        callers: dict[str, list] = {}
        callees: dict[str, list] = {}
        for r in rels:
            if isinstance(r, dict):
                frm = r.get("from_", "") or r.get("from", "")
                to  = r.get("to", "")
                kind = r.get("kind", "")
            else:
                frm  = r.from_ or ""
                to   = r.to or ""
                kind = r.kind or ""
            if kind == "calls":
                callers.setdefault(to, []).append(frm)
                callees.setdefault(frm, []).append(to)
        self._callers_index = callers
        self._callees_index = callees

    def check_staleness(self) -> dict:
        """Check if working tree files have changed compared to the indexed snapshot."""
        try:
            from rekipedia.storage.sqlite_store import SqliteStore
            from rekipedia.utils.staleness import check_index_staleness
            if not self.db_path.exists():
                return {"is_stale": False, "banner": ""}
            with SqliteStore(self.db_path) as s:
                repo_root = self._rekipedia_dir.parent
                return check_index_staleness(repo_root, s)
        except Exception:
            return {"is_stale": False, "banner": ""}


def _sym_to_dict(s) -> dict:
    return {
        "name": s.name if hasattr(s, "name") else s.get("name", ""),
        "file": s.file if hasattr(s, "file") else s.get("file", ""),
        "kind": s.kind if hasattr(s, "kind") else s.get("kind", ""),
    }


def _handle_tool(name: str, args: dict, cache: _StoreCache) -> str:
    try:
        if not cache.available:
            return json.dumps({"error": "No rekipedia DB found. Run reki scan first."})

        if name == "get_context":
            file_arg = args.get("file", "")
            syms = cache.symbols_for_file(file_arg)
            sym_names = [_sym_to_dict(s)["name"] for s in syms]
            sym_name_set = set(sym_names)
            file_rels = []
            for r in cache.rels:
                if isinstance(r, dict):
                    frm  = r.get("from_", "") or r.get("from", "")
                    to   = r.get("to", "")
                    kind = r.get("kind", "")
                    conf = r.get("confidence", 1.0)
                    ev_tag = r.get("evidence_tag", "EXTRACTED")
                else:
                    frm  = r.from_ or ""
                    to   = r.to or ""
                    kind = r.kind or ""
                    conf = getattr(r, "confidence", 1.0)
                    ev_tag = getattr(r, "evidence_tag", "EXTRACTED")
                if frm in sym_name_set:
                    file_rels.append({
                        "from": frm,
                        "to": to,
                        "kind": kind,
                        "confidence": conf,
                        "evidence_tag": ev_tag
                    })
            return json.dumps({"symbols": sym_names[:50], "relationships": file_rels[:100]})

        elif name == "search_nodes":
            matches = [_sym_to_dict(s) for s in cache.search_by_name(args.get("query", ""))]
            return json.dumps({"matches": matches})

        elif name == "get_relationships":
            symbol = args.get("symbol", "")
            callers, callees = cache.callers_callees(symbol)
            return json.dumps({"symbol": symbol, "callers": callers, "callees": callees})

        elif name == "get_knowledge_gaps":
            from rekipedia.analysis.graph_analysis import _build_knowledge_gaps
            class _R:
                pass
            r = _R()
            r.symbols = cache.symbols
            r.relationships = cache.rels
            gaps = _build_knowledge_gaps(r)
            return json.dumps({"knowledge_gaps": gaps})

        elif name == "get_hub_nodes":
            from rekipedia.analysis.graph_analysis import _build_hub_nodes
            hubs = _build_hub_nodes(cache.rels, cache.symbols, top_n=args.get("top_n", 10))
            return json.dumps({"hub_nodes": hubs})

        elif name == "get_impact":
            from rekipedia.analysis.impact import compute_impact
            result = compute_impact(args.get("file", ""), cache.rels, cache.symbols, depth=args.get("depth", 2))
            return json.dumps(result)

        elif name == "get_transitive_impact":
            from rekipedia.analysis.impact import compute_transitive_impact
            result = compute_transitive_impact(
                args.get("target_symbol", ""),
                cache.rels,
                cache.symbols,
                depth=args.get("depth", 5),
                direction=args.get("direction", "callers"),
            )
            return json.dumps(result)

        elif name == "ask":
            question = args.get("question", "")
            repo_path = Path(args.get("repo") or Path.cwd())
            out_dir = repo_path / ".rekipedia"
            if not out_dir.exists():
                return json.dumps({"error": "No .rekipedia dir found. Run reki scan first."})
            from rekipedia.models.contracts import LLMConfig
            from rekipedia.orchestrator.run_ask import run_ask
            answer = run_ask(question, repo_path, out_dir, llm_config=LLMConfig())
            return json.dumps({"answer": answer})

        elif name == "list_wiki_pages":
            repo_path = Path(args.get("repo") or Path.cwd())
            wiki_dirs = [repo_path / ".rekipedia" / "wiki", repo_path / "docs" / "wiki"]
            pages = []
            for wiki_dir in wiki_dirs:
                if wiki_dir.is_dir():
                    for p in wiki_dir.glob("*.md"):
                        pages.append({"name": p.stem, "path": str(p)})
            pages.sort(key=lambda x: x["name"])
            return json.dumps({"pages": pages})

        elif name == "get_wiki_page":
            page_arg = args.get("page", "").lower()
            repo_path = Path(args.get("repo") or Path.cwd())
            wiki_dirs = [repo_path / ".rekipedia" / "wiki", repo_path / "docs" / "wiki"]
            for wiki_dir in wiki_dirs:
                if wiki_dir.is_dir():
                    for p in sorted(wiki_dir.glob("*.md")):
                        if page_arg in p.stem.lower():
                            return json.dumps({"page": p.stem, "content": p.read_text(encoding="utf-8")})
            # Not found — collect available stems
            available = []
            for wiki_dir in wiki_dirs:
                if wiki_dir.is_dir():
                    available.extend(p.stem for p in wiki_dir.glob("*.md"))
            available.sort()
            return json.dumps({"error": "Page not found", "available": available})

        elif name == "get_god_nodes":
            from rekipedia.analysis.graph_analysis import compute_god_nodes
            from collections import defaultdict
            top_n = args.get("top_n", 10)
            pairs = compute_god_nodes(cache.rels, top_n=top_n)
            in_deg: dict[str, int] = defaultdict(int)
            out_deg: dict[str, int] = defaultdict(int)
            for r in cache.rels:
                frm = r.get("from_", "") if isinstance(r, dict) else (r.from_ or "")
                to  = r.get("to", "")   if isinstance(r, dict) else (r.to or "")
                if frm:
                    out_deg[frm] += 1
                if to:
                    in_deg[to] += 1
            god_nodes = [
                {"name": sym_name, "in_degree": in_deg[sym_name],
                 "out_degree": out_deg[sym_name], "score": score}
                for sym_name, score in pairs
            ]
            return json.dumps({"god_nodes": god_nodes})

        elif name == "shortest_path":
            from rekipedia.analysis.graph_analysis import compute_shortest_path
            result = compute_shortest_path(
                args.get("from", ""),
                args.get("to", ""),
                cache.rels,
            )
            return json.dumps(result)

        elif name == "get_community":
            from rekipedia.analysis.graph_communities import detect_communities
            symbol = args.get("symbol", "")
            edges = []
            for r in cache.rels:
                frm = r.get("from_", "") if isinstance(r, dict) else (r.from_ or "")
                to  = r.get("to", "")   if isinstance(r, dict) else (r.to or "")
                if frm and to:
                    edges.append((frm, to))
            community_map = detect_communities(edges)
            if symbol not in community_map:
                return json.dumps({"error": f"Symbol '{symbol}' not found in graph", "members": []})
            cid = community_map[symbol]
            members = sorted(k for k, v in community_map.items() if v == cid)
            return json.dumps({"community_id": cid, "members": members})

        elif name == "detect_changes":
            import subprocess as _sp
            repo_arg = args.get("repo") or str(Path.cwd())
            staged   = bool(args.get("staged", False))
            base     = args.get("base")

            repo_path = Path(repo_arg).resolve()
            # Verify git repo
            chk = _sp.run(["git", "rev-parse", "--git-dir"],
                          capture_output=True, text=True, cwd=repo_path)
            if chk.returncode != 0:
                return json.dumps({"error": "Not a git repository"})

            def _git_changed(extra: list[str]) -> list[str]:
                r = _sp.run(["git", "diff", "--name-only"] + extra,
                            capture_output=True, text=True, cwd=repo_path)
                return [f.strip() for f in r.stdout.splitlines() if f.strip()]

            if base:
                changed = _git_changed([base, "HEAD"])
            elif staged:
                changed = _git_changed(["--cached"])
            else:
                seen: set[str] = set()
                changed = []
                for f in _git_changed(["--cached"]) + _git_changed([]):
                    if f not in seen:
                        seen.add(f)
                        changed.append(f)

            # Filter generated files
            changed = [f for f in changed if not f.startswith(".rekipedia/")]
            if not changed:
                return json.dumps({"changed_files": [], "impacts": [], "summary": "No uncommitted changes"})

            # Build symbol-by-file index
            sym_by_file: dict[str, list[str]] = {}
            for s in cache.symbols:
                d = _sym_to_dict(s)
                f = d.get("file") or ""
                n = d.get("name") or ""
                if f and n:
                    sym_by_file.setdefault(f, []).append(n)

            def _risk(n: int) -> str:
                return "HIGH" if n >= 5 else ("MEDIUM" if n >= 2 else "LOW")

            try:
                from rekipedia.analysis.impact import compute_transitive_impact as _cti
                has_impact = True
            except ImportError:
                has_impact = False

            impacts = []
            for cf in changed:
                syms = sym_by_file.get(cf, [])
                if not syms or not has_impact:
                    impacts.append({
                        "file": cf,
                        "symbols": syms,
                        "risk": "LOW",
                        "total_affected": 0,
                        "affected_files": [],
                    })
                    continue
                all_affected: set[str] = set()
                all_affected_files: set[str] = set()
                for sym in syms:
                    res = _cti(sym, cache.rels, cache.symbols, depth=5, direction="both")
                    callers = res.get("results", res.get("affected_symbols", []))
                    for c in callers:
                        if isinstance(c, dict):
                            all_affected.add(c.get("symbol", ""))
                            if c.get("file"):
                                all_affected_files.add(c["file"])
                        elif isinstance(c, str):
                            all_affected.add(c)
                impacts.append({
                    "file": cf,
                    "symbols": syms[:20],
                    "risk": _risk(len(all_affected)),
                    "total_affected": len(all_affected),
                    "affected_files": sorted(all_affected_files)[:20],
                })

            impacts.sort(key=lambda x: x["total_affected"], reverse=True)
            return json.dumps({
                "changed_files": changed,
                "impacts": impacts,
                "summary": f"{len(changed)} changed file(s), highest risk: {impacts[0]['risk'] if impacts else 'NONE'}",
            })

        return json.dumps({"error": f"Unknown tool: {name}"})

    except Exception as exc:
        return json.dumps({"error": str(exc)})


def write_mcp_json(repo_root: Path):
    """Write / update .mcp.json at the repo root after a scan.

    Idempotent — safe to call on every scan.
    Skips silently if the file already exists with the correct content.
    """
    mcp_json_path = repo_root / ".mcp.json"
    config = {
        "mcpServers": {
            "rekipedia": {
                "command": "reki",
                "args": ["mcp"],
                "description": "rekipedia codebase knowledge — ask questions, search symbols, get impact analysis, browse wiki pages",
            }
        }
    }
    content = json.dumps(config, indent=2) + "\n"
    try:
        if mcp_json_path.exists() and mcp_json_path.read_text() == content:
            return  # already up to date
        mcp_json_path.write_text(content)
    except OSError:
        pass  # non-fatal — MCP server still works without the file


def _write(obj: dict):
    print(json.dumps(obj), flush=True)


def run_mcp_server(output_dir: str = "."):
    """Run MCP JSON-RPC 2.0 stdio server."""
    cache = _StoreCache(output_dir)

    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
        except json.JSONDecodeError:
            continue

        req_id  = req.get("id")
        method  = req.get("method", "")
        params  = req.get("params", {})

        if method == "initialize":
            _write({"jsonrpc": "2.0", "id": req_id, "result": {
                "protocolVersion": "2024-11-05",
                "capabilities": {"tools": {}},
                "serverInfo": {"name": "rekipedia", "version": "1.0.0"},
            }})
        elif method == "tools/list":
            _write({"jsonrpc": "2.0", "id": req_id, "result": {"tools": TOOLS}})
        elif method == "tools/call":
            result_text = _handle_tool(params.get("name", ""), params.get("arguments", {}), cache)
            stale = cache.check_staleness()
            if stale.get("is_stale"):
                try:
                    parsed = json.loads(result_text)
                    if isinstance(parsed, dict) and "_staleness_warning" not in parsed:
                        parsed["_staleness_warning"] = stale.get("banner")
                        result_text = json.dumps(parsed)
                except Exception:
                    pass
            _write({"jsonrpc": "2.0", "id": req_id, "result": {
                "content": [{"type": "text", "text": result_text}]
            }})
        elif method == "notifications/initialized":
            continue  # notifications require no response
        else:
            _write({"jsonrpc": "2.0", "id": req_id, "error": {"code": -32601, "message": "Method not found"}})
